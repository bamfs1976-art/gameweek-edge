#!/usr/bin/env node
/* Vendor the rotation signal from the Bookings Desk — and prove the bytes.
 *
 *   node scripts/vendor-rotation.mjs                 # fetch from source, re-vendor
 *   node scripts/vendor-rotation.mjs --check         # verify what is committed (offline)
 *   node scripts/vendor-rotation.mjs --check --remote # re-fetch and fail if drifted
 *   node scripts/vendor-rotation.mjs --refresh       # pull the live calendar only
 *
 * WHAT IS VENDORED AND WHY. Three files from bamfs1976-art/pl-bookings, the
 * repo that fitted the model:
 *
 *   vendor/rotation.js           the module. No dependencies, no DOM, no fetch,
 *                                no state — which is the only reason copying it
 *                                is honest rather than a fork waiting to happen.
 *   vendor/rotation_model.js     the fitted coefficients, generated over there.
 *   vendor/pl_other_fixtures.js  cup and European dates for the current season.
 *
 * WHY COPY RATHER THAN FETCH AT RUNTIME. The desk is a different site with a
 * different deploy cadence; a <script src> pointed at it would put another
 * origin on the critical path of a page that has to work on a phone at a
 * ground with no signal, and the Content-Security-Policy would then have to
 * name a host this app does not control. Same reasoning as vendor.js.
 *
 * WHY IT IS A SCRIPT AND NOT A PASTE. A copied file is a file that drifts.
 * Upstream refits the model, or re-harvests the calendar, and this repo keeps
 * shipping last month's coefficients with nothing to say so. So each payload's
 * SHA-256 is recorded in scripts/vendor-rotation.sha256.json, `--check` runs
 * offline in CI over the committed bytes, and `--check --remote` re-fetches
 * from the source and fails when the copy no longer matches it.
 *
 * THE THREE FILES DRIFT DIFFERENTLY, and conflating them is the trap:
 *
 *   rotation.js and rotation_model.js are PINNED to a commit. Drift in either
 *   is a fault — a hand-edit here, or a deliberate upstream change that has to
 *   be adopted on purpose by re-running this script and re-reading the guard.
 *
 *   pl_other_fixtures.js is LIVE DATA and is *expected* to move. Cup rounds
 *   and European group stages are drawn progressively, so the calendar is only
 *   ever known a few weeks out and upstream re-harvests it. Failing CI because
 *   the football calendar advanced would be a check that trains people to
 *   ignore it, so remote drift on this file asks for a refresh rather than
 *   calling the repo broken. What it DOES fail on is the opposite and more
 *   dangerous condition: a calendar that has stopped moving. See --check.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(root, 'vendor');
const MANIFEST = join(root, 'scripts', 'vendor-rotation.sha256.json');

const check = process.argv.includes('--check');
const remote = process.argv.includes('--remote');
const refresh = process.argv.includes('--refresh');

/* ── the source ────────────────────────────────────────────────────────────
 *
 * PINNED TO A COMMIT, not to a branch. A branch name here would mean the
 * recorded hash and the bytes it describes could disagree the next time
 * anybody ran this, which is the entire point of recording the hash.
 *
 * A NOTE ON WHERE THIS COMMIT LIVES. 5ab0bfc is the head of the source repo's
 * `claude/la-liga-booking-research-x5h55f` branch, NOT of `main` — none of the
 * three files exists on main yet. That has one consequence worth stating in
 * the file that depends on it: the desk's daily data-refresh workflow only
 * harvests pl_other_fixtures.js on that same unmerged branch, so until it
 * merges the upstream calendar is frozen at this commit and `--refresh` will
 * keep returning identical bytes. The freshness assertion in `--check` is what
 * notices that, rather than us assuming a refresh is running.
 */
const SOURCE = {
  owner: 'bamfs1976-art',
  repo: 'pl-bookings',
  /* Full SHA. An abbreviated ref would resolve differently as the repo grows. */
  commit: '5ab0bfcbfb437b98755f7469bd9533d59220c792',
  branch: 'claude/la-liga-booking-research-x5h55f',
};
const RAW = 'https://raw.githubusercontent.com/' + SOURCE.owner + '/' + SOURCE.repo + '/';

const FILES = [
  {
    id: 'rotation',
    from: 'assets/rotation.js',
    to: 'rotation.js',
    pinned: true,
    what: 'the module — PLDRotation.rotationRisk and the rest-day primitives',
  },
  {
    id: 'model',
    from: 'data/rotation_model.js',
    to: 'rotation_model.js',
    pinned: true,
    what: 'the fitted coefficients, generated by the desk\'s build-rotation-model.mjs',
  },
  {
    id: 'other-fixtures',
    from: 'data/pl_other_fixtures.js',
    to: 'pl_other_fixtures.js',
    pinned: false,
    what: 'cup and European dates for the current season — live input, refreshed upstream',
  },
];

function sha256(s) { return createHash('sha256').update(s, 'utf8').digest('hex'); }

/* ── the provenance header ─────────────────────────────────────────────────
 *
 * Generated, never hand-written, and NOT part of what the hash covers — the
 * hash is of the upstream payload and nothing else, so re-wording the
 * attribution can never look like tampered code. `payload()` below strips it
 * again by finding the sentinel end marker.
 */
const HEAD_END = ' * ── end vendored header ──';

function header(f, hash, fetched) {
  return [
    '/* VENDORED — do not edit this file.',
    ' *',
    ' * ' + f.what,
    ' *',
    ' * source   ' + SOURCE.owner + '/' + SOURCE.repo + '  ' + f.from,
    ' * commit   ' + SOURCE.commit,
    ' * branch   ' + SOURCE.branch,
    ' * sha256   ' + hash,
    ' * fetched  ' + fetched,
    ' *',
    ' * Re-vendor with: node scripts/vendor-rotation.mjs',
    ' * Verify with:    node scripts/vendor-rotation.mjs --check',
    HEAD_END,
    ' */',
    '',
  ].join('\n');
}

/* The upstream bytes, with our generated header removed. */
function payload(text) {
  const i = text.indexOf(HEAD_END);
  if (i === -1) return text;                    /* not one of ours: hash it whole */
  const j = text.indexOf('\n', i);
  /* j ends the marker line; k ends the comment-closing line after it. */
  const k = text.indexOf('\n', j + 1);
  return text.slice(k + 1);
}

function localPath(f) { return join(VENDOR, f.to); }

function readLocal(f) {
  const p = localPath(f);
  if (!existsSync(p)) throw new Error('vendor/' + f.to + ' is missing. Run: node scripts/vendor-rotation.mjs');
  return readFileSync(p, 'utf8');
}

async function fetchSource(f, ref) {
  const url = RAW + ref + '/' + f.from;
  const r = await fetch(url, { headers: { 'user-agent': 'gameweek-edge/vendor-rotation' } });
  if (!r.ok) {
    throw new Error('fetching ' + f.from + ' at ' + ref.slice(0, 12) + ' returned HTTP ' + r.status +
      '.\n  ' + url +
      '\n  The commit is on an unmerged branch upstream; if that branch was deleted or ' +
      'force-pushed, this vendoring has lost its source and the pin must be moved deliberately.');
  }
  return await r.text();
}

/* ── how far ahead the calendar actually reaches ───────────────────────────
 *
 * THE STALENESS CAVEAT, made mechanical. Cup rounds and European group stages
 * are drawn progressively, so early in a season the calendar is only known two
 * to six weeks out. A vendored snapshot that has stopped being refreshed does
 * not announce itself: it simply reports fewer and fewer congested clubs until
 * every side reads as well rested, which is the single most misleading thing
 * this signal could do. Counting the days from today to the last fixture in
 * the file is the cheapest honest measure of that.
 */
function horizonDays(text, now = Date.now()) {
  let last = -Infinity;
  for (const m of text.matchAll(/d:"([^"]+)"/g)) {
    const t = Date.parse(m[1]);
    if (isFinite(t) && t > last) last = t;
  }
  if (!isFinite(last)) return null;
  return Math.round((last - now) / 86400000);
}

function countFixtures(text) {
  return [...text.matchAll(/\{c:"/g)].length;
}

/* ── modes ─────────────────────────────────────────────────────────────── */

function readManifest() {
  if (!existsSync(MANIFEST)) {
    throw new Error('scripts/vendor-rotation.sha256.json is missing — nothing records what the ' +
      'vendored bytes are meant to be. Run: node scripts/vendor-rotation.mjs');
  }
  return JSON.parse(readFileSync(MANIFEST, 'utf8'));
}

async function doCheck() {
  const man = readManifest();
  let bad = 0;

  if (man.commit !== SOURCE.commit) {
    console.error('the manifest was written against commit ' + man.commit + ' but this script ' +
      'pins ' + SOURCE.commit + ' — re-vendor so the two agree');
    bad++;
  }

  for (const f of FILES) {
    const text = readLocal(f);
    const got = sha256(payload(text));
    const rec = man.files && man.files[f.id];
    if (!rec) { console.error('no recorded hash for ' + f.id); bad++; continue; }

    if (got !== rec.sha256) {
      console.error(f.id + ' (vendor/' + f.to + ') does not match the recorded sha256.\n' +
        '  recorded ' + rec.sha256 + '\n  on disk   ' + got + '\n' +
        '  Vendored code is a copy of somebody else\'s file, byte for byte. It must not be ' +
        'hand-edited here — fix it upstream and re-run: node scripts/vendor-rotation.mjs');
      bad++;
      continue;
    }
    /* The header must name the thing the hash covers, or the provenance is a
       comment rather than a claim. */
    for (const need of [SOURCE.commit, rec.sha256, f.from]) {
      if (!text.includes(need)) {
        console.error(f.id + ' provenance header does not carry "' + need + '"');
        bad++;
      }
    }
  }

  /* ── the live input, and whether it is still alive ──────────────────────
   *
   * TWO DIFFERENT CONDITIONS, and telling them apart is the whole job here.
   *
   * A SHORT HORIZON IS NOT A FAULT. Cup rounds and European group stages are
   * drawn progressively, so in August the calendar genuinely only reaches a
   * few weeks out — today it is two League Cup rounds and a single Conference
   * League tie. Failing on that would fail every pre-season, and a check that
   * cries wolf every August is a check nobody reads by September. The app
   * already has the honest answer for it: `known:false`, rendered as "no
   * previous competitive match" rather than as a rested side.
   *
   * A CALENDAR THAT HAS STOPPED BEING PULLED *IS* A FAULT, and it is the one
   * that hurts, because it looks identical from the inside — fewer and fewer
   * clubs read as congested until every side looks rested and the signal has
   * quietly inverted. What separates the two is not the horizon but the AGE of
   * the copy: how long since anything pulled it. That is what fails here.
   */
  const calFile = FILES.find((f) => f.id === 'other-fixtures');
  const cal = readLocal(calFile);
  const days = horizonDays(cal);
  const n = countFixtures(cal);
  const rec = (man.files || {})['other-fixtures'] || {};
  const age = rec.fetched
    ? Math.round((Date.now() - Date.parse(rec.fetched)) / 86400000) : null;

  if (days == null || n === 0) {
    console.error('vendor/pl_other_fixtures.js contains no parseable fixture dates at all — ' +
      'the calendar this signal rests on is empty, and every club would read as well rested');
    bad++;
  }
  if (age == null) {
    console.error('the manifest does not record when the calendar was last fetched, so there is ' +
      'no way to tell a thin calendar from an abandoned one. Run: node scripts/vendor-rotation.mjs --refresh');
    bad++;
  } else if (age > STALE_DAYS) {
    console.error('vendor/pl_other_fixtures.js was last pulled ' + age + ' days ago.\n' +
      '  This is the live input and it is meant to be pulled daily. Left alone it decays ' +
      'silently: fewer and fewer clubs read as congested until every side looks rested, which ' +
      'is the most misleading thing this signal can do.\n' +
      '  Refresh with: node scripts/vendor-rotation.mjs --refresh\n' +
      '  If that returns identical bytes, the upstream harvest has stopped — see the note on ' +
      'SOURCE in this file.');
    bad++;
  } else if (days != null && days < 0) {
    /* Every fixture in the file is in the past. Whatever the reason, the
       calendar can no longer answer the question for anybody: every club falls
       back to known:false, and a signal that is unknown for all twenty clubs
       is not a signal. This one IS a failure, however recently it was pulled. */
    console.error('every fixture in vendor/pl_other_fixtures.js is in the past — the last one was ' +
      Math.abs(days) + ' days ago. The calendar has expired entirely, so every club now reports ' +
      'known:false and the signal has nothing left to say.\n' +
      '  Refresh with: node scripts/vendor-rotation.mjs --refresh');
    bad++;
  } else if (days != null && days < THIN_DAYS) {
    /* Reported, deliberately not failed. */
    console.log('note: the calendar reaches only ' + days + ' days out (' + n + ' fixtures, pulled ' +
      age + ' days ago). Expected while cup and European rounds are still being drawn — clubs with ' +
      'no previous competitive match report known:false and must be shown as unknown, not as rested.');
    /* A thin calendar that has ALSO not moved in a long time is a different
       story: not a season waiting on its draws, but a harvest that has stopped.
       Reported rather than failed because it is a condition upstream, not a
       fault in this repo — but reported loudly, because from inside this repo
       the two look identical and only this line tells them apart. */
    const upstreamAge = rec.changed
      ? Math.round((Date.now() - Date.parse(rec.changed)) / 86400000) : null;
    if (upstreamAge != null && upstreamAge > STALE_UPSTREAM_DAYS) {
      console.log('WARNING: those bytes have not changed in ' + upstreamAge + ' days despite being ' +
        'pulled ' + age + ' days ago. A thin calendar that never moves is an upstream harvest that ' +
        'has stopped, not a season waiting on its draws — and from here the two look identical.\n' +
        '  The harvest step for this file lives on ' + SOURCE.branch + ', which is not merged to ' +
        'main upstream, so nothing is refreshing it. Until it merges this calendar is frozen and ' +
        'the signal will read known:false for more and more clubs as the season moves past it.');
    }
  }

  if (remote) await remoteDrift(man);

  if (bad) process.exit(1);
  console.log('vendor-rotation --check OK: ' + FILES.length + ' files at ' + SOURCE.commit.slice(0, 7) +
    ', every sha256 matching; calendar carries ' + n + ' fixtures and reaches ' + days + ' days out');
}

/* Fail if the pinned copies have drifted from the source; report, but do not
   fail, when the live calendar has moved — that is what it is supposed to do. */
async function remoteDrift(man) {
  let bad = 0;
  for (const f of FILES) {
    const want = payload(readLocal(f));
    let there;
    try {
      there = await fetchSource(f, f.pinned ? SOURCE.commit : SOURCE.branch);
    } catch (e) {
      console.error('could not re-fetch ' + f.from + ': ' + e.message);
      bad++;
      continue;
    }
    if (sha256(there) === sha256(want)) continue;

    if (f.pinned) {
      console.error(f.id + ' has DRIFTED from ' + SOURCE.owner + '/' + SOURCE.repo + ' at ' +
        SOURCE.commit.slice(0, 7) + '.\n' +
        '  The vendored copy is no longer the file it claims to be. Either it was edited here, ' +
        'or the pinned commit no longer resolves to the same bytes.\n' +
        '  Re-vendor deliberately and re-read scripts/check-rotation.mjs: node scripts/vendor-rotation.mjs');
      bad++;
    } else {
      console.log('note: the upstream calendar on ' + SOURCE.branch + ' has moved on from the ' +
        'vendored copy. That is expected — cup and European rounds are drawn progressively.\n' +
        '  Pull it with: node scripts/vendor-rotation.mjs --refresh');
    }
  }
  if (bad) process.exit(1);
}

async function doVendor(only) {
  mkdirSync(VENDOR, { recursive: true });
  const man = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : {};
  const files = man.files || {};
  const fetched = new Date().toISOString().slice(0, 10);

  for (const f of FILES) {
    if (only && f.id !== only) continue;
    /* Pinned files come from the commit; the live calendar comes from the tip
       of the branch that harvests it, because pinning live data to a commit
       would freeze the very thing that has to move. */
    const ref = f.pinned ? SOURCE.commit : SOURCE.branch;
    const body = await fetchSource(f, ref);
    const hash = sha256(body);
    /* `fetched` is when WE last pulled; `changed` is when the bytes last
       actually moved. Keeping both is what separates "our refresh job died"
       from "the upstream harvest died" — a daily pull that keeps returning
       identical bytes would otherwise look perfectly healthy from here, which
       is exactly the state this vendoring is in today. */
    const prev = files[f.id];
    const changed = (prev && prev.sha256 === hash && prev.changed) ? prev.changed : fetched;
    writeFileSync(localPath(f), header(f, hash, fetched) + body);
    files[f.id] = { path: f.from, sha256: hash, pinned: f.pinned, fetched, changed, ref };
    const kb = (body.length / 1024).toFixed(1);
    console.log('  ' + f.id.padEnd(16) + kb.padStart(6) + ' KB  ' + hash.slice(0, 16) + '…');
  }

  writeFileSync(MANIFEST, JSON.stringify({
    source: SOURCE.owner + '/' + SOURCE.repo,
    commit: SOURCE.commit,
    branch: SOURCE.branch,
    files,
  }, null, 2) + '\n');
  console.log('vendor/ written; scripts/vendor-rotation.sha256.json updated');
}

/* How many days a copy of the live calendar may go unpulled before it counts
   as abandoned rather than merely quiet. The upstream harvest runs daily, so a
   week of silence is already a broken pipeline; three days keeps the failure
   close enough to the cause to be diagnosable. */
const STALE_DAYS = 3;

/* How long the upstream bytes may stay identical before a thin calendar is
   better explained by a stopped harvest than by an undrawn cup round. */
const STALE_UPSTREAM_DAYS = 10;

/* Below this horizon the calendar cannot separate a congested club from a
   rested one, and the app should be saying so rather than implying rest. Six
   weeks is the upper end of how far cup and European draws are known. Reported,
   never failed — in August it is the truth about the season, not about us. */
const THIN_DAYS = 21;

try {
  if (check) await doCheck();
  else if (refresh) await doVendor('other-fixtures');
  else await doVendor(null);
} catch (e) {
  console.error(String((e && e.message) || e));
  process.exit(1);
}
